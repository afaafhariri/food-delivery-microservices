#!/usr/bin/env bash
# Applies k8s/overlays/prod on the k3s VM, with the public hostname and image
# tag filled in. Run as root on the VM from the repo copy; normally called by
# scripts/cloud-deploy.sh:
#   sudo bash k8s/vm/deploy.sh <host> <image-tag>
#
# The database password is generated once and kept in /etc/quickbite/secrets.env
# (root-only), so re-deploys never change it.
set -euo pipefail

HOST="${1:?usage: deploy.sh <host> <image-tag>}"
TAG="${2:?usage: deploy.sh <host> <image-tag>}"
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PROD="$REPO/k8s/overlays/prod"
OVERLAY="$REPO/k8s/overlays/cloud" # generated here, git-ignored
NS=quickbite

log() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
k() { k3s kubectl "$@"; }

[[ $EUID -eq 0 ]] || { echo "run as root" >&2; exit 1; }

if [[ ! -s /etc/quickbite/secrets.env ]]; then
  log "Generating database password (/etc/quickbite/secrets.env)"
  install -d -m 700 /etc/quickbite
  (umask 077; printf 'username=quickbite\npassword=%s\n' "$(openssl rand -hex 24)" > /etc/quickbite/secrets.env)
fi
install -m 600 /etc/quickbite/secrets.env "$PROD/secrets.env"

log "Writing overlay for host $HOST, image tag $TAG"
mkdir -p "$OVERLAY"
{
  cat <<EOF
# Generated by k8s/vm/deploy.sh. Edit k8s/overlays/prod instead.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../prod
patches:
  - target:
      kind: Ingress
      name: api-gateway
    patch: |-
      - op: replace
        path: /spec/rules/0/host
        value: $HOST
      - op: replace
        path: /spec/tls/0/hosts/0
        value: $HOST
images:
EOF
  # Re-tag every image the prod overlay points at.
  grep -E '^\s*newName:' "$PROD/kustomization.yaml" | awk '{print $2}' | while read -r image; do
    printf '  - name: %s\n    newTag: %s\n' "$image" "$TAG"
  done
} > "$OVERLAY/kustomization.yaml"

k apply -f "$REPO/k8s/base/namespace.yaml"

# Private GHCR packages: scripts/cloud-deploy.sh creates the "ghcr" secret when
# GHCR_TOKEN is set. The default ServiceAccount hands it to every pod.
if k -n "$NS" get secret ghcr >/dev/null 2>&1; then
  k -n "$NS" patch serviceaccount default -p '{"imagePullSecrets":[{"name":"ghcr"}]}'
fi

existed=false
k -n "$NS" get deployment api-gateway >/dev/null 2>&1 && existed=true

log "Applying"
k apply -k "$OVERLAY"

# A moving tag does not change the pod spec, so restart to pull new images.
if [[ "$TAG" == latest && "$existed" == true ]]; then
  log "Restarting deployments to pull :latest"
  k -n "$NS" rollout restart deployment
fi

fail() {
  echo
  echo "Deployment did not become ready. Current state:" >&2
  k -n "$NS" get pods -o wide || true
  echo
  k -n "$NS" get events --sort-by=.lastTimestamp | tail -25 || true
  exit 1
}

log "Waiting for Postgres and Kafka"
k -n "$NS" rollout status statefulset/postgres --timeout=5m || fail
k -n "$NS" rollout status statefulset/kafka --timeout=5m || fail

log "Waiting for the services"
for d in restaurant-service customer-service delivery-service order-service api-gateway; do
  k -n "$NS" rollout status "deployment/$d" --timeout=8m || fail
done

k -n "$NS" get pods -o wide
k -n "$NS" get ingress,certificate 2>/dev/null || true
